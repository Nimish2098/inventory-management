CREATE TABLE user_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    name VARCHAR(255) NOT NULL,
    CONSTRAINT uk_user_account_email UNIQUE (email)
);

CREATE TABLE customer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    email VARCHAR(255),
    owner_id BIGINT,
    CONSTRAINT uk_customer_owner_email UNIQUE (owner_id, email),
    CONSTRAINT fk_customer_owner FOREIGN KEY (owner_id) REFERENCES user_account (id)
);

CREATE TABLE warehouse (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(255),
    name VARCHAR(255),
    capacity INTEGER,
    active BOOLEAN NOT NULL,
    owner_id BIGINT,
    CONSTRAINT uk_warehouse_owner_code UNIQUE (owner_id, code),
    CONSTRAINT fk_warehouse_owner FOREIGN KEY (owner_id) REFERENCES user_account (id)
);

CREATE TABLE product (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(255),
    name VARCHAR(255),
    category VARCHAR(255),
    reorder_level BIGINT,
    lead_time_days INTEGER,
    owner_id BIGINT,
    CONSTRAINT uk_product_owner_sku UNIQUE (owner_id, sku),
    CONSTRAINT fk_product_owner FOREIGN KEY (owner_id) REFERENCES user_account (id)
);

CREATE TABLE inventory_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    warehouse_id BIGINT NOT NULL,
    quantity BIGINT NOT NULL,
    bin VARCHAR(255),
    CONSTRAINT uk_inventory_item_product_warehouse UNIQUE (product_id, warehouse_id),
    CONSTRAINT fk_inventory_item_product FOREIGN KEY (product_id) REFERENCES product (id),
    CONSTRAINT fk_inventory_item_warehouse FOREIGN KEY (warehouse_id) REFERENCES warehouse (id)
);

CREATE TABLE stock_movement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventory_item_id BIGINT NOT NULL,
    quantity_change BIGINT,
    type VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_stock_movement_inventory_item FOREIGN KEY (inventory_item_id) REFERENCES inventory_item (id)
);

CREATE TABLE customer_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    status VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_customer_order_customer FOREIGN KEY (customer_id) REFERENCES customer (id)
);

CREATE TABLE order_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    warehouse_id BIGINT NOT NULL,
    quantity BIGINT NOT NULL,
    CONSTRAINT fk_order_item_order FOREIGN KEY (order_id) REFERENCES customer_order (id),
    CONSTRAINT fk_order_item_product FOREIGN KEY (product_id) REFERENCES product (id),
    CONSTRAINT fk_order_item_warehouse FOREIGN KEY (warehouse_id) REFERENCES warehouse (id)
);
